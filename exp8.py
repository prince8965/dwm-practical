# Experiment no 8 : Implementation of Hierarchical Clustering using Agglomerative Clustering
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.preprocessing import StandardScaler
from sklearn.datasets import load_iris
from sklearn.metrics import silhouette_score
from sklearn.cluster import AgglomerativeClustering
from scipy.cluster.hierarchy import dendrogram,linkage

# load dataset
iris = load_iris()

df = pd.DataFrame(iris.data , columns=iris.feature_names)
print('\nOriginal Datasets: \n' , df.sample(5))

# scaled using Standardization method
scaler = StandardScaler()
x_scaled = scaler.fit_transform(df)

# create linkage
linked = linkage(x_scaled , method='ward')

# plot dendrogram
plt.figure(figsize=(10 , 5))
dendrogram(
    linked,
    truncate_mode='lastp',
    p=30,
    leaf_rotation=90,
    leaf_font_size=10,
    show_contracted=True
)

plt.title('Hierarchical Cluster Dendrogram')
plt.xlabel('Number of CLusters')
plt.ylabel('Distance')
plt.show()

# Apply Agglomerative clustering
model = AgglomerativeClustering(
    n_clusters=3,
    linkage='ward',
    metric='euclidean'
)

cluster_labels = model.fit_predict(x_scaled)

df['Clusters'] = cluster_labels


print('\nDatasets with Clusters: \n' , df.sample(5))

# plotting clusters gen by HC
plt.figure(figsize=(6,6))
plt.scatter(
    x_scaled[: , 0],
    x_scaled[: , 1],
    c=cluster_labels,
    cmap='viridis',
    s=80
)

plt.title('Clusters Generated by Hierarchical Clustering')
plt.xlabel('Sepal Length')
plt.ylabel('Sepal Width')
plt.colorbar(label='Clusters')
plt.show()

# Calculate the Silhouette Score
score = silhouette_score(x_scaled , cluster_labels)
print('\nSilhouette score : ' , round(score , 4))


# Count the no of items in each clusters
cluster_count = df['Clusters'].value_counts().sort_index()
print('\nNumber of Objects in each Clusters')
print(cluster_count)